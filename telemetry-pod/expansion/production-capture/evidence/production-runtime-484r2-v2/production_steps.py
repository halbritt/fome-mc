"""The steps of the single j6b2 preparation run, inside the AGENTEE-466 image (production_run.sh). Stops at the
first failure; never retries. Each step's exit status is printed on its own line.

1. build.py EXPORT --out /work/cap: the capture, generated by the pinned producer;
2. the generated composition copied into this run's own fome-mc copy, then build.py EXPORT --check: the capture
   reproduces byte for byte (the same files are committed afterwards);
3. pipeline.py: the preparation, emission and native checks (ROUTER_CHECKOUT is the image's own /opt/kicad-route);
4. runtime_receipt.py observe: the runtime identities and the runtime validation of the prepared campaign.
"""
import ast
import re
import shutil
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
W = Path('/work')
EXPORT, CAP, PIPE = W / 'export', W / 'cap', W / 'pipe'
SCOPE = HERE.parent / 'requirements/rev3-microsd/compiled'


def step(name, argv):
    print(f'=== {name}: {" ".join(map(str, argv))}', flush=True)
    rc = subprocess.run([str(a) for a in argv]).returncode
    print(f'\n{name}-exit={rc}', flush=True)
    if rc:
        sys.exit(rc)


py = ['/usr/bin/python3', '-B']
step('build-out', [*py, HERE / 'build.py', EXPORT, '--out', CAP])
generated = ast.literal_eval(re.search(r'GENERATED = (\[.*?\])', (HERE / 'build.py').read_text(), re.S).group(1))
for name in generated:
    shutil.copyfile(CAP / 'composition' / name, HERE / 'composition' / name)
shutil.copyfile(CAP / 'reconstruction.json', HERE / 'reconstruction.json')
step('build-check', [*py, HERE / 'build.py', EXPORT, '--check'])
step('pipeline', [*py, HERE / 'pipeline.py', EXPORT, '/opt/kicad-route', SCOPE, CAP, PIPE])
step('observe', [*py, HERE / 'runtime_receipt.py', '--runtime', HERE / 'runtime/agentee-484r2.json', 'observe', PIPE / 'prepared',
                  W / 'observation.json', EXPORT])  # AGENTEE-487 H4: explicit runtime selection
print('\nsteps=done', flush=True)
